"""Short 09 "The Porch Light Code": the sound cue sheet. Wholesome, a little eerie in the middle (beats 8-12), relief from
beat 14, warm from beat 15. The switch is the story: every flash is a crisp, countable click (on) and a softer clack (off).
Every time comes from the picture's events and cut list (video/src/short09_porch/events09.json, regenerated by the lead as
shots are tuned) or from words in video/src/short09_porch/timing.json (at(beat, "word")); never a typed second.
Effects + score:  python3 -I episodes/09_porch_light/sfx09.py      (sfx_gen/*.wav; rerun when events09.json changes)
Mix:              python3 -I pipeline/mix.py episodes/09_porch_light/cues.py episodes/09_porch_light/mix.wav
Level:            python3 -I pipeline/music_level.py episodes/09_porch_light/cues.py -9
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
from cuekit import Cues  # noqa: E402

c = Cues("short09_porch", HERE)
at, atE, PS, PE = c.at, c.atE, c.PS, c.PE
EV = json.load(open(ROOT / "video" / "src" / "short09_porch" / "events09.json"))
G = lambda n: str(HERE / "sfx_gen" / f"{n}.wav")                     # our synthesised sounds (sfx09.py)
G6 = lambda n: str(ROOT / "episodes" / "06_reflection" / "sfx_gen" / f"{n}.wav")
S = lambda n: str(ROOT / "sfx" / f"{n}.mp3")

VOICE = str(HERE / "master_voiceover.wav")
END = EV["end"]
LENGTH = END
MUSIC_DUCK_DB = 6
SFX_MAX = 4.0

# ---- THE MUSIC LEVEL: one number. Measured about 9 dB under the voice with music_level.py (the owner may ask for 15 dB:
# change only this and remix; no re-render).
MUSIC_DB = 1.6
# ---- the switch: one number for the click (on); the clack (off) sits CLACK_UNDER dB below it
SWITCH_DB = -7
CLACK_UNDER = 2.5

ev = lambda k: [e for e in EV["events"] if e["kind"] == k]
one = lambda k: ev(k)[0]

# ---------------------------------------------------------------- places (beds change on the cuts, short fades)
spans = []                                                            # merge neighbouring cuts of the same place
for cut in EV["cuts"]:
    if spans and spans[-1][0] == cut["place"] and abs(spans[-1][2] - cut["t0"]) < 1e-3:
        spans[-1][2] = cut["t1"]
    else:
        spans.append([cut["place"], cut["t0"], cut["t1"]])
PLACE_BEDS = {
    "street_night": [(G6("crickets"), -30), ("amb_wind_soft_02", -40), ("amb_city_evening_01", -42)],
    "street_dusk": [(S("street_birds"), -30), ("amb_wind_soft_02", -40)],
    "store": [(G("store_hum"), -34), ("crowd_murmur_02", -38), ("amb_room_tone_03", -38)],
    "our_room": [("amb_room_tone_01", -32), (G("tv_murmur"), -36)],
    "bell_hall": [("amb_room_tone_01", -32), ("clock_tick_02", -38)],
}
XF = 0.06
BEDS = []
for place, a, b in spans:
    fi = 0.0 if a < 0.01 else XF
    fo = 0.0 if b > END - 0.01 else XF
    for name, db in PLACE_BEDS[place]:
        BEDS.append((name, max(0.0, a - (XF if fi else 0)), b + (XF if fo else 0) / 2, db, fi, fo))

# Dad snoring: only while our living room is on screen, inside the snore window
sn = one("snore")
for place, a, b in spans:
    lo, hi = max(a, sn["t"]), min(b, sn["t1"])
    if place == "our_room" and hi - lo > 0.1:
        BEDS.append((G("snore"), lo, hi, -27, 0.05, 0.08))
# the wall clock in our room (beat 7)
for e in ev("clock_tick"):
    BEDS.append(("clock_tick_03", e["t"], e["t1"], -31, 0.03, 0.08))

# ---------------------------------------------------------------- music: our own score (sfx09.py), one bed, start to end
BEDS.append((G("score09"), 0.0, END, MUSIC_DB, 0.0, 0.0, "music"))

# ---------------------------------------------------------------- effects (all from events09.json)
SFX = []
add = lambda name, t, db, keep=None: SFX.append((name, max(0.0, t), db) + ((keep,) if keep else ()))

# THE SWITCH: ours (the hook from across the street, Dad, ME) and Mr. Bell's (a touch lower)
for e in ev("switch_click") + ev("switch_clack"):
    who = "bell" if "Bell" in e["note"] else "ours"
    far = "across the street" in e["note"]
    on = e["kind"] == "switch_click"
    db = SWITCH_DB - (0 if on else CLACK_UNDER) - (2 if far else 0)
    add(G(f"sw_{who}_{'click' if on else 'clack'}"), e["t"], db)

for e in ev("door_close"):
    add("door_close_01", e["t"] - 0.03, -26, 0.7)                     # Mr. Bell's door, across the street
for e in ev("door_open"):
    add("door_creak_open_01", e["t"] - 0.05, -27, 1.6)                # a gentle creak
for e in ev("cart_rattle"):
    add(G("cart_rattle"), e["t"], -22)


def steps(e, name, gap, db, lead=0.0):
    t, k = e["t"] + lead, 0
    while t < e["t1"] - 0.05:
        add(G(name), t, db - (1.5 if k % 2 else 0)); t += gap; k += 1


for e in ev("steps_hurry_shop"):
    steps(e, "step_tile", 0.19, -25, 0.05)
for e in ev("steps_hurry_path"):
    steps(e, "step_path", 0.2, -26, 0.03)
for e in ev("clock_flip"):
    add(G("chime_nine"), e["t"], -24, 2.4)
for e in ev("tiptoe"):                                                 # socks on wood, the boards creak twice
    steps(e, "step_sock", 0.34, -33, 0.05)
    add(G("creak_1"), e["t"] + (e["t1"] - e["t"]) * 0.2, -30)
    add(G("creak_3"), e["t"] + (e["t1"] - e["t"]) * 0.65, -31)
for e in ev("coat_whoosh"):
    add(G("coat_rustle"), e["t"] - 0.15, -29)
    add("whoosh_short_01", e["t"] - 0.12, -33, 0.4)
for e in ev("slipper_steps_fast"):
    steps(e, "step_slipper", 0.15, -27, 0.02)
for e in ev("knock_that_never_comes"):                                 # NO knock: a held breath, a tiny cloth rustle
    add(G("cloth_rustle"), e["t"] - 0.05, -37)
for e in ev("laugh_two_men"):
    add(G("laugh_two_men"), e["t"], -17, e["t1"] - e["t"] + 0.8)
for e in ev("question_pop"):
    add("pop_01", e["t"], -26, 0.3)
